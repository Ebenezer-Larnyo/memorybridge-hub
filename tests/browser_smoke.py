"""Headless browser smoke test; not a clinical or accessibility audit."""
import os,sys
from playwright.sync_api import sync_playwright,expect
base=os.environ.get('TEST_URL','http://127.0.0.1:8000/')
with sync_playwright() as p:
 browser=p.chromium.launch()
 page=browser.new_page(viewport={'width':390,'height':844})
 errors=[]
 page.on('pageerror',lambda error:errors.append(str(error)))
 page.goto(base)
 expect(page).to_have_title('Naviboa Hub | Dementia Resource & Support Hub')
 expect(page.locator('h1')).to_contain_text('What do you need help with today?')
 expect(page.locator('#mira h2')).to_have_text('Meet Naviboa AI')
 expect(page.locator('footer')).to_contain_text('Naviboa Hub')
 expect(page.locator('.trustbar')).to_contain_text('Daily resource discovery')
 assert page.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()") == '#5a2e85'
 expect(page.locator('#theme option[value=sage]')).to_have_text('Lavender (default)')
 expect(page.locator('#results article')).not_to_have_count(0,timeout=15000)
 expect(page.locator('#status')).to_contain_text('resources')
 expect(page.locator('#quality-summary')).to_contain_text('0 of')
 expect(page.locator('.review-badge').first).not_to_have_text('Human reviewed')
 page.locator('#topic').select_option('Respite & services')
 expect(page.locator('#results article')).not_to_have_count(0)
 page.locator('#advanced-filters').evaluate('(el)=>el.open=true')
 page.locator('#reviewed-only').check()
 expect(page.locator('#results')).to_contain_text('No currently human-reviewed resources')
 page.locator('#reviewed-only').uncheck()
 page.locator('#filters button[type=reset]').click()
 page.locator('#region').select_option('Ghana')
 expect(page.locator('#results')).to_contain_text('Ghana')
 page.locator('nav a[data-view=community]').click()
 page.locator('#spanish').click()
 page.locator('#advanced-filters').evaluate('(el)=>el.open=true')
 expect(page.locator('#results')).to_contain_text('Spanish')
 page.locator('nav a[data-view=companion]').click()
 page.locator('#mira-input').fill('respite care')
 page.locator('#mira-form button[type=submit]').click()
 expect(page.locator('#mira-links article')).not_to_have_count(0)
 page.locator('#mira-input').fill('sudden confusion')
 page.locator('#mira-form button[type=submit]').click()
 expect(page.locator('#mira-reply')).to_contain_text('urgent')
 expect(page.locator('#mira-links article')).to_have_count(0)
 expect(page.locator('.crisis')).to_contain_text('1-800-272-3900')
 expect(page.locator('#mira-reply')).to_contain_text('911')
 page.locator('nav a[data-view=resources]').click()
 page.locator('#advanced-filters').evaluate('(el)=>el.open=true')
 page.locator('#filters button[type=reset]').click()
 page.locator('#topic').select_option('End of life & hospice')
 expect(page.locator('#results article')).not_to_have_count(0)
 page.locator('#filters button[type=reset]').click()
 page.locator('#community-focus').select_option('Black')
 expect(page.locator('#status')).to_be_visible()
 page.locator('#filters button[type=reset]').click()
 page.locator('nav a[data-view=companion]').click()
 page.locator('#mira-input').fill('hospice options')
 page.locator('#mira-form button[type=submit]').click()
 expect(page.locator('#mira-links article')).not_to_have_count(0)
 expect(page.locator('#glossary dt')).not_to_have_count(0)
 page.locator('#comfort summary').click()
 page.locator('#large').click()
 expect(page.locator('#large')).to_have_attribute('aria-pressed','true')
 page.locator('#contrast').click()
 expect(page.locator('#contrast')).to_have_attribute('aria-pressed','true')
 page.locator('#theme').select_option('dusk')
 assert page.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()") == '#e7bcff'
 expect(page.locator('html')).to_have_attribute('data-theme','dusk')
 page.locator('#theme').select_option('paper')
 assert page.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()") == '#663b8b'
 page.locator('#theme').select_option('sage')
 page.locator('#comfort summary').click()
 page.locator('nav a[data-view=care]').click()
 page.locator('#remember').check()
 page.locator('#routine-check input').first.check()
 page.reload()
 expect(page.locator('#routine-check input').first).to_be_checked()
 page.locator('#forget').click()
 expect(page.locator('#routine-check input').first).not_to_be_checked()
 expect(page.locator('#remember')).not_to_be_checked()
 page.locator('#simple').click()
 expect(page.locator('#find')).not_to_be_visible()
 page.locator('#simple').click()
 expect(page.locator('#daily')).to_be_visible()
 page.locator('nav a[data-view=resources]').click()
 expect(page.locator('#find')).to_be_visible()
 expect(page.locator('#mira')).not_to_be_visible()
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'mobile overflow'
 page.set_viewport_size({'width':1280,'height':900})
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'desktop overflow'
 page.goto(base+'es.html')
 expect(page.locator('html')).to_have_attribute('lang','es')
 expect(page).to_have_title('Naviboa Hub en español')
 expect(page.locator('article')).not_to_have_count(0)
 assert not errors, errors
 browser.close()
print('Browser smoke checks passed')
